// UI language: English (default) and Russian. Entries are strings, functions of params,
// or plural forms (en: [one, many], ru: [one, few, many]).

let lang = 'en';

export function setLang(l) {
  lang = l === 'ru' ? 'ru' : 'en';
}

export function getLang() {
  return lang;
}

export function getLocale() {
  return lang === 'ru' ? 'ru-RU' : 'en-US';
}

function pluralIndex(n) {
  const a = Math.abs(n);
  if (lang === 'en') return a === 1 ? 0 : 1;
  const m100 = a % 100;
  const m10 = a % 10;
  if (m100 > 10 && m100 < 20) return 2;
  if (m10 === 1) return 0;
  if (m10 >= 2 && m10 <= 4) return 1;
  return 2;
}

// t('key') / t('key', params). Missing Russian entries fall back to English, then to the key.
export function t(key, params) {
  const v = DICT[lang][key] ?? DICT.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(params ?? {}) : v;
}

// Plural word only: tp('pools', 3) -> 'pools' / 'пула'.
export function tp(key, n) {
  const forms = DICT[lang][key] ?? DICT.en[key];
  if (!Array.isArray(forms)) return key;
  return forms[Math.min(pluralIndex(n), forms.length - 1)];
}

// For tests: the keys a language defines.
export function dictKeys(l) {
  return Object.keys(DICT[l] || {});
}

// Fills static markup: data-i18n (text), data-i18n-title, data-i18n-placeholder, data-i18n-aria.
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((n) => (n.textContent = t(n.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((n) => (n.title = t(n.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((n) => (n.placeholder = t(n.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-aria]').forEach((n) => n.setAttribute('aria-label', t(n.dataset.i18nAria)));
}

